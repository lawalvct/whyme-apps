// Generates theme.css (CSS variables + Tailwind v4 @theme) from src/index.ts.
// Run with `pnpm tokens:build` after changing tokens.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = readFileSync(join(root, 'src/index.ts'), 'utf8');

const colorsBlock = source.match(/export const colors = \{([\s\S]*?)\} as const;/);
if (!colorsBlock) throw new Error('colors block not found in src/index.ts');

const colors = [...colorsBlock[1].matchAll(/(\w+):\s*'(#[0-9A-Fa-f]{6})'/g)].map(([, name, value]) => [
  name.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`),
  value,
]);

const css = `/* Generated by packages/tokens/scripts/build-css.mjs — do not edit by hand. */
@theme {
${colors.map(([name, value]) => `  --color-${name}: ${value};`).join('\n')}
  --font-sans: "Inter", ui-sans-serif, system-ui, sans-serif;
}
`;

writeFileSync(join(root, 'theme.css'), css);
console.log(`theme.css written (${colors.length} colours)`);
